// Helper to generate smooth realistic chart curve
function generatePoints(base: number, volatility: number, count: number, trendUp: boolean): { time: string; price: number }[] {
  const points: { time: string; price: number }[] = [];
  let curr = base * (trendUp ? 0.97 : 1.03);
  
  const step = (base - curr) / count;
  for (let i = 0; i < count; i++) {
    const randomWalk = (Math.random() - 0.48) * volatility;
    curr += step + randomWalk;
    const hour = Math.floor(9.5 + (i / count) * 6.5);
    const minute = Math.floor(((9.5 + (i / count) * 6.5) % 1) * 60);
    const timeStr = `${hour.toString().padStart(2, '0')}:${minute.toString().padStart(2, '0')}`;
    points.push({ time: timeStr, price: Number(curr.toFixed(2)) });
  }
  points[points.length - 1].price = base;
  return points;
}

